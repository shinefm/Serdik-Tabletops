import asyncio,json
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path='/usr/bin/google-chrome')
        pg=await b.new_page(viewport={'width':390,'height':844},device_scale_factor=2)
        errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.add_init_script(path='/home/claude/serdik-tabletops/dev/test/mockfb.js')
        await pg.goto('file:///home/claude/serdik-tabletops/dev/fbapp/test_out/index.html'); await pg.wait_for_timeout(1500)
        await pg.click('#createBtn'); await pg.wait_for_timeout(800)
        await pg.evaluate("""async()=>{const r=db.doc('games/'+cur.gid);const s=(await r.get()).data();s.players.push(newPlayer('u_dina','Dina'),newPlayer('u_budi','Budi'));s.timer=180;s.v++;await r.set(s);}""")
        await pg.wait_for_timeout(400); await pg.click('[data-act="start"]'); await pg.wait_for_timeout(1500)
        await pg.evaluate("closeModal()")
        ids=json.loads(await pg.evaluate("JSON.stringify(cur.st.players.map(p=>p.id))")); me=ids.index(await pg.evaluate("myId")); d=ids.index('u_dina'); bu=ids.index('u_budi')
        async def setst(js):
            await pg.evaluate("""async()=>{const r=db.doc('games/'+cur.gid);const s=(await r.get()).data();"""+js+""";s.v++;await r.set(s);}"""); await pg.wait_for_timeout(700)
        async def st(js): return await pg.evaluate(js)
        print('hostBtn visible:',await st("$('#hostBtn').style.display!=='none'"))
        await setst(f"s.turn={d};s.turnAt=Date.now()-20000")
        await pg.click('#hostBtn'); await pg.wait_for_timeout(300); await pg.screenshot(path='host_modal.png')
        print('rows:',await st("document.querySelectorAll('#modal .hrow').length"),'btns:',await st("[...document.querySelectorAll('#modal button')].map(b=>b.textContent.trim())"))
        await pg.click('[data-act="hpause"]'); await pg.wait_for_timeout(900)
        l1=await st("tmrLeft(cur.st)"); await pg.wait_for_timeout(1500); l2=await st("tmrLeft(cur.st)")
        print('paused:',await st("!!cur.st.paused"),'frozen:',l1==l2,round(l1/1000),'bar:',await st("($('#afkBar')||{}).textContent"))
        await pg.screenshot(path='host_paused.png')
        r=await st("(async()=>{myId='u_dina';try{await commitOnline(s=>doMove(s,meIdx(s),{type:'take',picks:{w:1,u:1,g:1}}));return 'moved'}catch(e){return e.message}finally{myId='u_me'}})()")
        print('dina move while paused:',r)
        print('skip while paused:',await st("(async()=>{try{await commitOnline(s=>hostOp(s,'skip'));return 'ok'}catch(e){return e.message}})()"))
        await pg.click('#hostBtn'); await pg.wait_for_timeout(300); await pg.click('#modal [data-act="hresume"]'); await pg.wait_for_timeout(900)
        print('resumed: left',round(await st("tmrLeft(cur.st)")/1000),'paused',await st("cur.st.paused"))
        await pg.click('#hostBtn'); await pg.wait_for_timeout(300); await pg.click('#modal [data-act="hskip"]'); await pg.wait_for_timeout(900)
        print('after skip turn',await st("cur.st.turn"),'(dina',d,') last',await st("JSON.stringify(cur.st.last)"))
        # dina diganti bot -> autopilot jalan saat gilirannya
        await pg.click('#hostBtn'); await pg.wait_for_timeout(300); await pg.click(f'#modal [data-act="hbot"][data-i="{d}"]'); await pg.wait_for_timeout(700)
        await setst(f"s.turn={d};s.turnAt=Date.now()"); await pg.wait_for_timeout(3500)
        print('dina auto:',await st(f"cur.st.players[{d}].auto"),'turn now',await st("cur.st.turn"),'last',await st("JSON.stringify(cur.st.last)"))
        # tuan rumah ganti dirinya dengan bot
        await pg.click('#hostBtn'); await pg.wait_for_timeout(300); await pg.click(f'#modal [data-act="hbot"][data-i="{me}"]'); await pg.wait_for_timeout(700)
        print('me auto:',await st(f"cur.st.players[{me}].auto"),'bar:',await st("($('#afkBar')||{}).textContent"))
        await pg.click('#hostBtn'); await pg.wait_for_timeout(300); await pg.click(f'#modal [data-act="hhuman"][data-i="{me}"]'); await pg.wait_for_timeout(700)
        print('me back:',await st(f"!!cur.st.players[{me}].auto"))
        # pindah tuan rumah
        await pg.click('#hostBtn'); await pg.wait_for_timeout(300); await pg.click(f'#modal [data-act="hhost"][data-i="{bu}"]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='host_confirm.png'); await pg.click('#modal [data-act="hhostok"]'); await pg.wait_for_timeout(1200)
        print('host now',await st("cur.st.host"),'btn visible',await st("$('#hostBtn').style.display!=='none'"))
        print('non-host op:',await st("(async()=>{try{await commitOnline(s=>hostOp(s,'pause'));return 'ok'}catch(e){return e.message}})()"))
        print('budi sees btn:',await st("(myId='u_budi',hostTick(),$('#hostBtn').style.display!=='none')")); await st("myId='u_me';hostTick()")
        print('errs',errs); await b.close()
asyncio.run(main())
